
def area(a):
    """
    Вычисляет площадь квадрата по длине стороны a.

        Параметры:
            a (int | float): длина стороны квадрата

        Возвращаемое значение:
            area (int | float): площадь квадрата

        Пример вызова:
            area(2)
    """
    return a * a


def perimeter(a):
    """
    Вычисляет периметр квадрата по длине стороны a.

        Параметры:
            a (int | float): длина стороны квадрата
        
        Возвращаемое значение:
            perimeter (int | float): периметр квадрата
        
        Пример вызова:
            perimeter(2)
    """
    return 4 * a
